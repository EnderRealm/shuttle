// runeWidth is how many columns r occupies: 0 for a mark that combines with
// the character before it, 2 for a wide character, 1 otherwise.
func runeWidth(r rune) int {
	if r < 0x300 {
		return 1
	}
	if unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf) || (r >= 0xFE00 && r <= 0xFE0F) {
		return 0
	}
	lo, hi := 0, len(wide)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < wide[mid][0]:
			hi = mid - 1
		case r > wide[mid][1]:
			lo = mid + 1
		default:
			return 2
		}
	}
	return 1
}

